@dataclass
class Project:
    pid: str
    name: str
    problem: str
    skills: list[str]
    industry: str
    result: str
    lang: str
    date: str
    sparse_readme: bool = False
    review: dict | None = None
    extra: dict = field(default_factory=dict)


def _describe(skill: str, rng: random.Random, implied_ratio: float) -> str:
    if skill in IMPLIED and rng.random() < implied_ratio:
        return IMPLIED[skill]
    return skill


def case_study_md(p: Project, persona: str, rng: random.Random) -> str:
    approach = ", ".join(_describe(s, rng, 0.55) for s in p.skills)
    return (
        f"<!-- {SYNTH_NOTE} -->\n# {p.name}\n\n"
        f"*Client industry: {p.industry} | Completed: {p.date} | Evidence id: {persona}:case:{p.pid}*\n\n"
        f"## The problem\nThe client was {p.problem}.\n\n"
        f"## What I did\nI scoped the work with the client, then built the solution using {approach}. "
        f"I kept the client in the loop with short weekly demos and wrote handover notes.\n\n"
        f"## Result\nThe project {p.result}.\n"
    )


def readme_md(p: Project, persona: str) -> str:
    if p.sparse_readme:
        return f"<!-- {SYNTH_NOTE} -->\n# {p.pid}-internal\n\nInternal tool. See code.\n"
    stack = "\n".join(f"- {s}" for s in p.skills)
    return (
        f"<!-- {SYNTH_NOTE} -->\n# {p.name.lower().replace(' ', '-')}\n\n"
        f"Source for the {p.name} engagement ({p.industry}).\n\n## Stack\n{stack}\n\n"
        f"## Run locally\n```bash\ncp .env.example .env\nmake dev\n```\n"
    )


def code_file(p: Project) -> str:
    if p.lang == "ts":
        lines = [TS_IMPORTS[s] for s in p.skills if s in TS_IMPORTS]
        body = "\nexport async function handler(req: unknown) {\n  // core logic for " + p.name + "\n  return { ok: true };\n}\n"
        return f"// {SYNTH_NOTE}\n" + "\n".join(lines) + "\n" + body
    if p.lang == "sql":
        tag = ", ".join(p.skills)
        return (f"-- {SYNTH_NOTE}\n-- tools: {tag}\nwith base as (\n  select customer_id, order_date, amount\n  from raw.orders\n)\n"
                "select date_trunc('month', order_date) as month, count(distinct customer_id) as customers, sum(amount) as revenue\n"
                "from base group by 1 order by 1;\n")
    lines = [CODE_IMPORTS[s] for s in p.skills if s in CODE_IMPORTS]
    return f"# {SYNTH_NOTE}\n" + "\n".join(lines) + f"\n\n\ndef main():\n    \"\"\"Entry point for {p.name}.\"\"\"\n    ...\n"


def make_review(p: Project, rng: random.Random) -> dict | None:
    if rng.random() > 0.6:
        return None
    rating = rng.choice([5.0, 5.0, 5.0, 4.8, 4.5, 4.0])
    text = rng.choice([
        f"Great work on our {p.industry} project. Communication was clear and the result {p.result}.",
        f"Delivered what was promised. {p.name} is now part of our daily workflow.",
        "Knew the tools well and asked the right questions before starting. Would hire again.",
        "Good work, a few days late on the final milestone but quality was high.",
    ])
    return {"rating": rating, "text": text, "client_industry": p.industry, "date": p.date}


def make_proposals(persona: str, projects: list[Project], rng: random.Random, n: int = 150) -> list[dict]:
    """Past proposals with outcomes. Outcome depends on hidden writing quality (documented in DATA_CARD)."""
    out = []
    for i in range(n):
        p = rng.choice(projects)
        specific = rng.random() < 0.5
        cites_evidence = rng.random() < 0.6
        concise = rng.random() < 0.55
        if specific:
            opening = rng.choice(SPECIFIC_OPENINGS).format(pain=p.problem, industry=p.industry, project=p.name, result=p.result)
        else:
            opening = rng.choice(GENERIC_OPENINGS)
        body = (f" For a similar job I used {', '.join(p.skills[:3])}." if cites_evidence else
                " I have worked with many technologies and can learn anything quickly.")
        close = " I can share a short plan for the first milestone." if concise else (
            " I am available 24/7, I guarantee 100% satisfaction, and I will deliver beyond expectations, "
            "with unlimited revisions and complete dedication to your success in every way.")
        score = 0.15 + 0.35 * specific + 0.25 * cites_evidence + 0.15 * concise + rng.uniform(-0.15, 0.15)
        outcome = "won" if score > 0.75 else "replied" if score > 0.5 else "ignored"
        d = date(2023, 1, 1) + timedelta(days=rng.randint(0, 1000))
        out.append({
            "evidence_id": f"{persona}:proposal:{i:04d}", "type": "proposal", "project": p.pid,
            "job_category": rng.choice(PERSONAS[persona]["categories"]), "client_industry": p.industry,
            "skills": p.skills[:3] if cites_evidence else [], "date": d.isoformat(), "outcome": outcome,
            "text": opening + body + close, "synthetic": True,
        })
    return out


def cv_text(persona: str, projects: list[Project]) -> tuple[str, list[str]]:
    meta = PERSONAS[persona]
    skills = sorted({s for p in projects for s in p.skills})
    lines = [meta["display_name"], meta["headline"], SYNTH_NOTE, "",
             f"Experience: {meta['years']} years freelancing.", "Skills: " + ", ".join(skills), "", "Selected projects:"]
    for p in projects[:8]:
        lines.append(f"- {p.name} ({p.industry}, {p.date[:4]}): {p.result}.")
    return "\n".join(lines), skills


def write_cv_pdf(text: str, path: Path) -> None:
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", size=10)
    for line in text.split("\n"):
        pdf.multi_cell(0, 5, line.encode("latin-1", "replace").decode("latin-1"), new_x="LMARGIN", new_y="NEXT")
    pdf.output(str(path))


def generate(out: Path, seed: int) -> None:
    for persona, rows in PROJECTS.items():
        rng = random.Random(f"{seed}-{persona}")
        root = out / persona
        for sub in ("case_studies", "repos"):
            (root / sub).mkdir(parents=True, exist_ok=True)
        projects: list[Project] = []
        for i, (name, problem, skills, industry, result, lang) in enumerate(rows):
            d = date(2021, 6, 1) + timedelta(days=rng.randint(0, 1600))
            p = Project(f"p{i:02d}", name, problem, skills, industry, result, lang, d.isoformat(),
                        sparse_readme=rng.random() < 0.25)
            p.review = make_review(p, rng)
            projects.append(p)
            (root / "case_studies" / f"{p.pid}.md").write_text(case_study_md(p, persona, rng))
            repo = root / "repos" / p.pid
            repo.mkdir(exist_ok=True)
            (repo / "README.md").write_text(readme_md(p, persona))
            (repo / f"main.{lang}").write_text(code_file(p))
        reviews = [{"evidence_id": f"{persona}:review:{p.pid}", "type": "review", "project": p.pid, **p.review,
                    "synthetic": True} for p in projects if p.review]
        proposals = make_proposals(persona, projects, rng)
        cv, skills = cv_text(persona, projects)
        (root / "cv.md").write_text(cv)
        write_cv_pdf(cv, root / "cv.pdf")
        profile = {"freelancer_id": persona, **PERSONAS[persona], "skills": skills, "synthetic": True}
        (root / "profile.json").write_text(json.dumps(profile, indent=2))
        (root / "reviews.json").write_text(json.dumps(reviews, indent=2))
        (root / "proposals.json").write_text(json.dumps(proposals, indent=2))
        # Ground truth used only by evaluation to build gold evidence labels; agents never read it.
        manifest = [{"project": p.pid, "name": p.name, "skills": p.skills, "industry": p.industry, "date": p.date,
                     "sparse_readme": p.sparse_readme, "has_review": p.review is not None} for p in projects]
        (root / "manifest.json").write_text(json.dumps(manifest, indent=2))
        won = sum(x["outcome"] == "won" for x in proposals)
