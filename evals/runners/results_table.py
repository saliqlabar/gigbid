"""Regenerates the B5 results table (README + report) from committed results files only.

    python -m evals.runners.results_table
Reads evals/results/rag_variants.json (retrieval) and outcomes_<name>.json (proposal quality, reply
rate, latency, cost). Writes evals/results/results_table.md and results_table.csv. A cell is "n/a"
when no results file measured it: numbers are never typed in by hand.
"""
from __future__ import annotations

import csv
import json

from evals.runners.common import RESULTS

COLS = ["Variant", "Evidence Recall@5", "nDCG@10", "Unsupported claims per proposal", "Judge score",
        "GigSim reply rate", "p95 latency (s)", "Cost per proposal (USD)"]


def _load(name: str) -> dict | None:
    p = RESULTS / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def _fmt(v, nd=3) -> str:
    return "n/a" if v is None else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def build() -> list[list[str]]:
    rag = (_load("rag_variants") or {}).get("results", {})
    rows = []
    outcome_files = sorted(p.stem for p in RESULTS.glob("outcomes_*.json"))
    by_variant = {}
    for name in outcome_files:
        d = _load(name)
        by_variant[d.get("rag_variant", name)] = (name, d)
    for variant in list(rag) + [v for v in by_variant if v not in rag]:
        r = rag.get(variant, {}).get("overall", {})
        o = by_variant.get(variant, (None, {}))[1].get("overall", {})
        rows.append([variant, _fmt(r.get("recall@5")), _fmt(r.get("ndcg@10")),
                     _fmt(o.get("unsupported_after_per_proposal")), _fmt(o.get("judge_mean"), 2),
                     _fmt(o.get("reply_rate")), _fmt(o.get("latency_p95_s"), 1), _fmt(o.get("usd_per_proposal"), 4)])
    return rows


def main() -> None:
    rows = build()
    md = ["| " + " | ".join(COLS) + " |", "|" + "---|" * len(COLS)] + ["| " + " | ".join(r) + " |" for r in rows]
    (RESULTS / "results_table.md").write_text(
        "<!-- generated by python -m evals.runners.results_table; do not edit -->\n" + "\n".join(md) + "\n")
    with (RESULTS / "results_table.csv").open("w", newline="") as f:
        csv.writer(f).writerows([COLS] + rows)
    print("\n".join(md))


if __name__ == "__main__":
    main()
